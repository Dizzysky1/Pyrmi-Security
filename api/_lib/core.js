const ymd = (t) => new Date(t).toISOString().slice(0, 10).replace(/-/g, '');
const num = (v, d) => (Number.isFinite(Number(v)) ? Number(v) : d);
const intEnv = (k, d) => { const n = parseInt(process.env[k], 10); return Number.isFinite(n) && n > 0 ? n : d; };
// When on, every ordinary project must register at least one allowed origin, and a project with none can't mint
// sessions (F-07). Off by default so turning it on is a deliberate step once existing projects have origins set
// and the create form collects them; an origin-bound project is already enforced regardless of this flag.
const requireOrigins = () => /^(1|true|on|yes)$/i.test(String(process.env.PYRMI_REQUIRE_ORIGINS || ''));

// Fixed-window counter: INCR, and set the TTL only on the first hit so the window actually expires.
// (Re-EXPIRE-ing on every call let an attacker keep a key pinned forever and lock the victim out of a limit.)
async function bump(key, ttl, limit) {
  const n = num(await kv.cmd('INCR', key), 1);
  if (n === 1) await kv.cmd('EXPIRE', key, ttl);
  return n > limit;
}

// Per-network limit for one kind of request. Limits can be changed with env vars (see README).
async function limitIp(ip, name, ttl, env, dflt, message) {
  const ipf = await C.fingerprint('ip', ip);
  if (await bump('ps:rl:' + name + ':' + ipf, ttl, intEnv(env, dflt))) {
    const e = httpError(429, 'rate_limited', message || 'Too many requests from your network. Try again in a few minutes.');
    e.retryAfter = ttl; // the window length, surfaced as Retry-After (F-23)
    throw e;
  }
}

// Secret-key lookup with a cap on wrong guesses per network, so nobody can hammer the key check.
// The right key always works: checking the cap first let anyone on a shared network (an office, a school, mobile
// CGNAT) lock the real owner out with a few junk keys (A2-05). Keys are 180 bits, so the cap is about load, not
// guessing.
async function projectForKey(sk, ip) {
  const project = await projectBySecretKey(sk);
  if (project) return project;
  const ipf = await C.fingerprint('ip', ip);
  if (await bump('ps:rl:badkey:' + ipf, 900, intEnv('PYRMI_BAD_KEYS_PER_IP', 20))) throw httpError(429, 'rate_limited', 'Too many wrong secret keys from your network. Try again later.');
  return null;
}

// pyrmi.com's own check on a request from one of its pages. Anything short of a clean accept is refused.
async function guardSite(token, ip) {
  if (String(process.env.PYRMI_SITE_GUARD || '').toLowerCase() === 'off') return null;
  const ipf = await C.fingerprint('ip', ip);
  const v = await verify(await loadProject(SITE.pid), { token, player: 'net-' + ipf.slice(0, 8) }, { ip });
  if (v.verdict === 'accept') return v;
  const e = httpError(403, 'blocked_by_pyrmi', 'Pyrmi flagged this request: ' + v.reasons.map((r) => r.text).join(' '));
  e.reasons = v.reasons.map((r) => r.code);
  throw e;
}

// ---- input cleaning ---------------------------------------------------------------------------------------------

function cleanName(s) {
  const v = String(s || '').replace(/[\u0000-\u001f<>]/g, '').trim().slice(0, 48);
  return v || 'Untitled project';
}

function cleanOrigins(list) {
  if (!Array.isArray(list)) list = String(list || '').split(/[\s,]+/);
  const out = [];
  for (const raw of list) {
    const s = String(raw || '').trim();
    if (!s) continue;
    let u; try { u = new URL(s); } catch (_) { throw httpError(400, 'bad_origin', 'Not a valid origin: ' + s.slice(0, 80)); }
    if (!/^https?:$/.test(u.protocol)) throw httpError(400, 'bad_origin', 'Origins must start with http:// or https://');
    if (!out.includes(u.origin)) out.push(u.origin);
  }
  return out.slice(0, 10);
}

function cleanPlayer(p) {
  const s = String(p == null ? '' : p).slice(0, 64).replace(/[^\w .\-@:#]/g, '_').trim();
  return s || 'anonymous';
}

function cleanSettings(patch, base) {
  const s = { ...base };
  const p = patch || {};
  const optNum = (k, lo, hi) => {
    if (!(k in p)) return;
    if (p[k] === null || p[k] === '') { s[k] = null; return; }
    const n = Number(p[k]);
    if (!Number.isFinite(n) || n < lo || n > hi) throw httpError(400, 'bad_setting', k + ' must be between ' + lo + ' and ' + hi);
    s[k] = n;
  };
  optNum('maxScore', 0, 1e15); optNum('maxScorePerSec', 0, 1e12);
  optNum('reviewAt', 1, 100); optNum('rejectAt', 1, 100); optNum('minDurationMs', 0, 864e5); optNum('sessionTtlSec', 60, 86400);
  for (const k of ['reviewAt', 'rejectAt', 'minDurationMs', 'sessionTtlSec']) if (s[k] === null) s[k] = DEFAULTS[k];
  if (s.reviewAt > s.rejectAt) throw httpError(400, 'bad_setting', 'reviewAt must not be above rejectAt');
  if ('strictClock' in p) s.strictClock = !!p.strictClock;
  if ('origins' in p) s.origins = cleanOrigins(p.origins);
  return s;
}

// Telemetry fields the browser script may report. These are ADVISORY: client telemetry is attacker-controlled,
// so it can only ADD risk (flag automation, scripted input, tampering), never prove a request is human. The hard
// floor is server-side and cannot be forged from the browser: the HMAC-signed session token, single-use replay
// protection, expiry, minimum duration (measured on the server), score caps and the rate limits. The network and
// browser a session started from are only compared on beacons, as the soft ip_changed / ua_changed signals.
// We used to also hand the page a per-session XOR "shape" key and treat a beacon that decoded cleanly as proof of
// a real client. That was security theatre: the key shipped to the browser, so anyone could read it from the public
// SDK and forge a clean beacon (risk 0). The key is no longer sent; beacons are plain JSON. Order matches the SDK.
const FIELDS = ['wd', 'hl', 'au', 'tp', 'dt', 'ut', 'ih', 'k', 'p', 'h', 'pt', 'gt', 'sh'];
// Legacy: decode a shaped+XOR beacon from a session created before the key was dropped. New sessions send plain JSON.
function decodeShaped(body, shape) {
  const enc = body && body[shape.n];
  if (typeof enc !== 'string' || enc.length > 8192) return null;
  const key = Buffer.from(shape.k, 'base64url'), raw = Buffer.from(enc, 'base64url');
  let json = '';
  for (let i = 0; i < raw.length; i++) json += String.fromCharCode((raw[i] ^ key[i % key.length] ^ (i * 7)) & 255);
  let obj; try { obj = JSON.parse(json); } catch (_) { return null; }
  if (!obj || typeof obj !== 'object') return null;
  const out = {};
  for (let i = 0; i < FIELDS.length; i++) { if (!(shape.f[i] in obj)) return null; out[FIELDS[i]] = obj[shape.f[i]]; }
  return out;
}
const KNOWN_SDK = new Set([SDK.hash, SDK.sourceHash, ...(SDK.previous || [])].filter(Boolean));

// Client signals are attacker-controlled: keep only known fields, with types and sizes forced.
function cleanSignals(raw) {
  const r = raw && typeof raw === 'object' ? raw : {};
  const n = (v) => Math.max(0, Math.min(1e6, Math.floor(num(v, 0))));
  const list = (v) => (Array.isArray(v) ? v : []).map((x) => String(x).replace(/[^\w.:-]/g, '').slice(0, 24)).filter(Boolean).slice(0, 10);
  const t = (v) => (Number.isFinite(Number(v)) && Number(v) >= 0 && Number(v) < 1e12 ? Number(v) : null);
  return { wd: !!r.wd, hl: !!r.hl, au: list(r.au), dt: n(r.dt), ut: n(r.ut), ih: n(r.ih), tp: list(r.tp), k: n(r.k), p: n(r.p), h: n(r.h), pt: t(r.pt), gt: t(r.gt),
    sh: typeof r.sh === 'string' ? r.sh.replace(/[^\w]/g, '').slice(0, 16) : null };
}

function mergeSignals(a, b) {
  const u = (x, y) => [...new Set([...(x || []), ...(y || [])])].slice(0, 10);
  return {
    wd: !!(a.wd || b.wd), hl: !!(a.hl || b.hl), au: u(a.au, b.au), tp: u(a.tp, b.tp),
    dt: Math.max(a.dt || 0, b.dt), ut: Math.max(a.ut || 0, b.ut), ih: Math.max(a.ih || 0, b.ih),
    k: Math.max(a.k || 0, b.k), p: Math.max(a.p || 0, b.p), h: Math.max(a.h || 0, b.h),
    uac: !!(a.uac || b.uac), ipc: !!(a.ipc || b.ipc),
  };
}

// ---- projects ---------------------------------------------------------------------------------------------------

function parseProject(pid, h) {
  if (!h || !h.pk) return null;
  let settings = {};
  try { settings = JSON.parse(h.settings || '{}'); } catch (_) { /* keep defaults */ }
  settings = { ...DEFAULTS, ...settings };
  const b = BUILTIN[pid];
  if (b) settings = { ...settings, ...b.settings, origins: [] };
  return { pid, name: h.name, publicKey: h.pk, created: num(h.created, 0), settings, demo: !!b,
    owner: h.owner || null, lastSession: num(h.ls, 0), lastVerify: num(h.lv, 0) };
}

async function loadProject(pid) {
  if (!/^[\w-]{1,40}$/.test(String(pid))) return null;
  if (BUILTIN[pid]) await ensureBuiltin(BUILTIN[pid]);
  return parseProject(pid, kv.pairs(await kv.cmd('HGETALL', 'ps:p:' + pid)));
}

const builtinReady = new Set();
async function ensureBuiltin(b) {
  if (builtinReady.has(b.pid)) return;
  await kv.pipeline([
    ['HSETNX', 'ps:p:' + b.pid, 'pk', b.publicKey],
    ['HSET', 'ps:p:' + b.pid, 'name', b.name],
    ['HSETNX', 'ps:p:' + b.pid, 'created', Date.now()],
    ['SET', 'ps:pk:' + b.publicKey, b.pid],
  ]);
  builtinReady.add(b.pid);
}

async function createProject(body, ip, owner) {
  if (String(process.env.PYRMI_SIGNUPS || '').toLowerCase() === 'off') throw httpError(403, 'signups_closed', 'New projects are paused on this server.');
  const name = cleanName(body.name);
  const settings = cleanSettings({ origins: body.origins || [] }, DEFAULTS);
  // A public key alone can mint sessions, so a project with no allowed origins is effectively open to any page.
  // When origin enforcement is on, make registering one a condition of creation (checked before the counter is
  // touched, so a rejected create can't poison the capacity count) (F-07).
  if (requireOrigins() && !settings.origins.length) throw httpError(400, 'origins_required', 'Register at least one allowed origin (the page URL that will start sessions) for this project.');
  const ipf = await C.fingerprint('ip', ip);
  if (await bump('ps:rl:newproj:' + ipf, DAY, intEnv('PYRMI_PROJECTS_PER_IP', 3))) throw httpError(429, 'rate_limited', 'Too many new projects from your network today.');
  const count = await kv.cmd('INCR', 'ps:projects');
  // Give the slot back on rejection: an over-cap attempt must not permanently inflate the counter (F-09).
  if (count > intEnv('PYRMI_MAX_PROJECTS', 500)) { await kv.cmd('DECR', 'ps:projects'); throw httpError(403, 'at_capacity', 'This server is not taking new projects right now.'); }
  const pid = 'p_' + C.randomId(9), pk = 'pk_' + C.randomId(18), sk = 'sk_' + C.randomId(30);
  await kv.pipeline([
    ['HSET', 'ps:p:' + pid, 'name', name, 'pk', pk, 'skh', C.sha256(sk), 'created', Date.now(), 'settings', JSON.stringify(settings), ...(owner ? ['owner', owner] : [])],
    ['SET', 'ps:pk:' + pk, pid],
    ['SET', 'ps:sk:' + C.sha256(sk), pid],
  ]);
  return { pid, name, publicKey: pk, secretKey: sk, settings };
}

async function projectByPublicKey(pk) {
  if (typeof pk !== 'string' || !/^pk_[\w-]{4,40}$/.test(pk)) return null;
  for (const b of Object.values(BUILTIN)) if (pk === b.publicKey) return loadProject(b.pid);
  const pid = await kv.cmd('GET', 'ps:pk:' + pk);
  return pid ? loadProject(pid) : null;
}

async function projectBySecretKey(sk) {
  if (typeof sk !== 'string' || !/^sk_[\w-]{20,60}$/.test(sk)) return null;
  const h = C.sha256(sk);
  const pid = await kv.cmd('GET', 'ps:sk:' + h);
  if (!pid) return null;
  // Only the key the project itself records is live. Two rotations racing (say, an attacker with a stolen key
  // hammering rotate) could each map a new key to the project while only one was stored, and the other was never
  // revoked by later rotations (A2-01). A stale ps:sk entry now opens nothing.
  if ((await kv.cmd('HGET', 'ps:p:' + pid, 'skh')) !== h) return null;
  return loadProject(pid);
}

async function updateSettings(project, patch) {
  if (project.demo) throw httpError(403, 'demo_locked', 'The demo project cannot be changed.');
  const settings = cleanSettings(patch, project.settings);
  const fields = ['settings', JSON.stringify(settings)];
  if (patch && 'name' in patch) fields.push('name', cleanName(patch.name));
  await kv.cmd('HSET', 'ps:p:' + project.pid, ...fields);
  return loadProject(project.pid);
}

async function rotateSecret(project, oldSk) {
  if (project.demo) throw httpError(403, 'demo_locked');
  const sk = 'sk_' + C.randomId(30);
  // Signed-in owners rotate without the old key, so drop whatever hash is stored on the project.
  const stored = await kv.cmd('HGET', 'ps:p:' + project.pid, 'skh');
  const oldHash = oldSk ? C.sha256(oldSk) : stored;
  await kv.pipeline([
    ['DEL', 'ps:sk:' + oldHash],
    ...(stored && stored !== oldHash ? [['DEL', 'ps:sk:' + stored]] : []), // one key per DEL: kv only prefixes the first
    ['SET', 'ps:sk:' + C.sha256(sk), project.pid],
    ['HSET', 'ps:p:' + project.pid, 'skh', C.sha256(sk)],
  ]);
  return sk;
}

// What an API response may show of a project (never the owner's account id).
function view(p) { const { owner, ...rest } = p; return rest; }

async function deleteProject(project) {
  if (project.demo) throw httpError(403, 'demo_locked');
  const pid = project.pid;
  const skh = await kv.cmd('HGET', 'ps:p:' + pid, 'skh');
  // Only give back a capacity slot for a project that was actually still there. A repeat delete of an already-gone
  // project must be a no-op, and the counter must never go negative (which would disable the cap) (F-13/F-14).
  const existed = num(await kv.cmd('EXISTS', 'ps:p:' + pid), 0);
  // "Delete site" is sold as deletion, so take the visitor and stats data with the project, not just the project
  // record. Read the recent-players index before dropping it to learn which per-player hashes to remove; the daily
  // stats/quota keys are day-stamped (<=35d TTL), so clear a generous window of them by day.
  const players = (await kv.cmd('ZRANGE', 'ps:plr:' + pid, 0, -1)) || [];
  const now = Date.now(), dayKeys = [];
  for (let d = 0; d <= 40; d++) { const day = ymd(now - d * DAY * 1000); dayKeys.push('ps:st:' + pid + ':' + day, 'ps:q:' + pid + ':' + day); }
  await kv.cmd('DEL', 'ps:sk:' + skh, 'ps:pk:' + project.publicKey, 'ps:p:' + pid, 'ps:ev:' + pid, 'ps:plf:' + pid, 'ps:plr:' + pid,
    ...players.map((m) => 'ps:pl:' + pid + ':' + m), ...dayKeys);
  if (existed) {
    const left = num(await kv.cmd('DECR', 'ps:projects'), 0);
    if (left < 0) await kv.cmd('SET', 'ps:projects', '0');
  }
}

// ---- sessions & signals -----------------------------------------------------------------------------------------

// A session token, and only a session token. OAuth state cookies are signed with the same key and format, and anyone
// can get one by starting a sign-in, so check the shape too (A2-07).
async function readSession(token) {
  const t = await C.readToken(token);
  return t && t.v === 1 && typeof t.p === 'string' && typeof t.s === 'string' && Number.isFinite(t.i) && Number.isFinite(t.e) ? t : null;
}

async function startSession(project, ctx) {
  const s = project.settings;
  // An allowed-origins list is a real binding: the request's Origin must be in it (a missing Origin is '' and so
  // never matches, which rejects bare non-browser callers too). This is enforced whenever a project has origins set.
  if (s.origins.length && !s.origins.includes(ctx.origin)) throw httpError(403, 'origin_not_allowed', 'This page is not on the project\'s allowed origins.');
  // A real browser always sends an Origin. Require one for ordinary projects so sessions can't be minted by a bare
  // script with no page behind it; the builtin site widget and public sandbox are exempt (F-07).
  if (!project.demo && !ctx.origin) throw httpError(403, 'origin_required', 'A browser Origin is required to start a session.');
  // With enforcement on, an ordinary project that never registered an origin stays open to any page (the check
  // above is vacuous for an empty list), so refuse to mint sessions for it until one is set (F-07). The per-project
  // daily cap below (ps:q, independent of IP) remains the backstop against quota drain in every case.
  if (requireOrigins() && !project.demo && !s.origins.length) throw httpError(403, 'origin_required', 'This project has no allowed origins registered; add one in the dashboard to start sessions.');
  const ipf = await C.fingerprint('ip', ctx.ip), uaf = await C.fingerprint('ua', ctx.ua || '');
  const now = Date.now(), day = ymd(now);
  if (await bump('ps:rl:sess:' + ipf, 600, intEnv('PYRMI_SESSIONS_PER_IP', 150))) throw httpError(429, 'rate_limited', 'Too many sessions from this network. Try again in a few minutes.');
  // Per-network share of the project's daily quota, so one source can't drain the whole project-wide limit
  // (sessions start from a public key, which anyone can read). Kept generous for real traffic behind a shared NAT.
  if (await bump('ps:qi:' + project.pid + ':' + ipf + ':' + day, 2 * DAY, intEnv('PYRMI_SESSIONS_PER_IP_PER_DAY', 2000))) throw httpError(429, 'quota', 'Too many sessions from this network for this project today.');
  if (await bump('ps:q:' + project.pid + ':' + day, 2 * DAY, intEnv('PYRMI_SESSIONS_PER_DAY', 20000))) throw httpError(429, 'quota', 'This project hit its daily session limit.');
  const sid = C.randomId(12), seed = C.randomUint32(), exp = now + s.sessionTtlSec * 1000;
  const token = await C.signToken({ v: 1, p: project.pid, s: sid, i: now, e: exp, seed, ih: ipf, uh: uaf });
  const stat = 'ps:st:' + project.pid + ':' + day;
  await kv.pipeline([
    ['HSET', 'ps:s:' + sid, 'p', project.pid, 'i', now, 'ih', ipf, 'uh', uaf, 'b', 0],
    ['EXPIRE', 'ps:s:' + sid, s.sessionTtlSec + 3600],
    ['HINCRBY', stat, 'sessions', 1], ['EXPIRE', stat, 35 * DAY],
    ['HSET', 'ps:p:' + project.pid, 'ls', now], // "your page is connected" on the dashboard
  ]);
  return { token, session: sid, seed, expiresAt: exp };
}

async function recordSignals(body, ctx) {
  const t = await readSession(body && body.token);
  if (!t) throw httpError(400, 'invalid_token');
  const now = Date.now();
  if (now > t.e + 3600e3) throw httpError(410, 'expired');
  const key = 'ps:s:' + t.s;
  const sess = kv.pairs(await kv.cmd('HGETALL', key));
  if (!sess.p) throw httpError(410, 'expired');
  if (num(sess.b, 0) >= MAX_BEACONS) return { ok: true, capped: true };
  let prev = {}; try { prev = JSON.parse(sess.sig || '{}'); } catch (_) { /* fresh */ }
  // Beacons are plain JSON under `signals`. Legacy sessions created before this change carry a shape key in `x`;
  // decode those too so an in-flight session keeps working across the deploy.
  let shape = null; try { shape = sess.x ? JSON.parse(sess.x) : null; } catch (_) { /* fresh */ }
  const raw = shape ? decodeShaped(body, shape) : body.signals;
  if (!raw || typeof raw !== 'object') {
    // Malformed telemetry is just dropped. We do NOT poison the session's verdict for it: a single bad or truncated
    // beacon (a flaky network, a racing tab close) must not permanently flag an otherwise fine session (was F-10).
    throw httpError(400, 'bad_signals', 'Telemetry could not be read.');
  }
  const sig = cleanSignals(raw);
  const merged = mergeSignals(prev, sig);
  if (sig.sh && !KNOWN_SDK.has(sig.sh)) merged.tp = [...new Set([...(merged.tp || []), 'pyrmi.js'])].slice(0, 10);
  if ((await C.fingerprint('ua', ctx.ua || '')) !== sess.uh) merged.uac = true;
  if ((await C.fingerprint('ip', ctx.ip)) !== sess.ih) merged.ipc = true;
  const mark = JSON.stringify({ pt: sig.pt, gt: sig.gt, st: now });
  const cmds = [['HSET', key, 'sig', JSON.stringify(merged), 'l', mark], ['HINCRBY', key, 'b', 1]];
  if (!sess.f) cmds.push(['HSET', key, 'f', mark]);
  // keep the first mark that carried game time, so time_warp has a span to measure
  if (sig.gt !== null && !sess.g) cmds.push(['HSET', key, 'g', mark]);
  await kv.pipeline(cmds);
  return { ok: true };
}

function assess(sess, settings, durationMs) {
  const out = [];
  const add = (code, detail) => out.push({ code, weight: WEIGHTS[code], detail });
  let sig = {}; try { sig = JSON.parse(sess.sig || '{}'); } catch (_) { /* none */ }
  if (!num(sess.b, 0)) add('no_client');
  if (sig.wd || sig.hl || (sig.au && sig.au.length)) add('automation', [sig.wd && 'webdriver', sig.hl && 'headless', ...(sig.au || [])].filter(Boolean).join(', '));
  if (sig.ut > 0) add('synthetic_input', sig.ut + ' scripted events');
  if (sig.ih > 0) add('inhuman_input', sig.ih + ' bursts');
  if (sig.tp && sig.tp.length) add('tampered_runtime', sig.tp.join(', '));
  if (sig.dt > 0) add('devtools_open');
  if (sig.uac) add('ua_changed');
  if (sig.ipc) add('ip_changed');
  let f = null, l = null, g = null;
  try { f = JSON.parse(sess.f || 'null'); l = JSON.parse(sess.l || 'null'); g = JSON.parse(sess.g || 'null'); } catch (_) { /* no marks */ }
  if (f && l && f.pt !== null && l.pt !== null) {
    const span = l.st - f.st;
    if (span >= 15000) {
      const r = (l.pt - f.pt) / span;
      if ((r > 1.33 || r < 0.75) && Math.abs((l.pt - f.pt) - span) > 4000) add('speed_hack', 'page clock ran at ' + r.toFixed(2) + 'x');
    }
  }
  if (g && l && g.gt !== null && l.gt !== null) {
    const span = l.st - g.st, game = (l.gt - g.gt) * 1000;
    if (span >= 8000 && game >= 0) {
      const r = game / span;
      if ((r > 1.3 && game - span > 3000) || (settings.strictClock && r < 0.7 && span - game > 3000)) add('time_warp', 'app clock ran at ' + r.toFixed(2) + 'x real time');
    }
  }
  if (durationMs !== null && durationMs > 20000 && (sig.k || 0) + (sig.p || 0) < 2) add('idle_input');
  return out;
}

// ---- verdicts ---------------------------------------------------------------------------------------------------

async function verify(project, body, ctx) {
  const now = Date.now(), s = project.settings;
  const reasons = [];
  const hard = (code, detail) => reasons.push({ code, weight: 100, detail });
  // The value is optional: leave it out to check an action that has no number (a sign-up, a vote, a form post).
  const hasScore = body.score !== undefined && body.score !== null && body.score !== '';
  const score = hasScore ? Number(body.score) : null;
  const durationMs = body.durationMs === undefined || body.durationMs === null ? null : Number(body.durationMs);
  const player = cleanPlayer(body.player !== undefined ? body.player : body.user);
  let sid = null, t = null, genuine = false;

  if (hasScore && (!Number.isFinite(score) || score < 0)) hard('bad_score');
  if (durationMs !== null && (!Number.isFinite(durationMs) || durationMs < 0)) hard('bad_score', 'durationMs');

  t = await readSession(body.token);
  // Rate-limit on something the caller can't freely multiply. The player name is caller-chosen, so keying only on it
  // let an attacker reset the limit by spraying new names (was F-12). Key on the session id from the (signed,
  // single-use) token when present, and fall back to the caller's network, so player is never the sole dimension.
  const rlKey = (t && t.s) ? 's:' + t.s : 'n:' + (ctx && ctx.ip ? await C.fingerprint('ip', ctx.ip) : 'none');
  if (await bump('ps:rl:v:' + project.pid + ':' + rlKey, 60, intEnv('PYRMI_VERIFIES_PER_MIN', 30))) hard('rate_limited');

  if (!t) hard('invalid_token');
  else if (t.p !== project.pid) hard('wrong_project');
  else if (now > t.e) { sid = t.s; hard('expired'); }
  else {
    sid = t.s;
    // Keep the marker for as long as the token itself can still be used, not the project's current TTL: lowering
    // sessionTtlSec after tokens were issued let the marker expire first and the same token pass again (A2-02).
    const fresh = await kv.cmd('SET', 'ps:used:' + sid, '1', 'NX', 'EX', Math.ceil(Math.max(0, t.e - now) / 1000) + 3600);
    if (fresh !== 'OK') hard('token_reused');
    const sess = kv.pairs(await kv.cmd('HGETALL', 'ps:s:' + sid));
    const genuineSess = sess.p === project.pid;
    // Measure elapsed time from the server-recorded session start, never the token's self-reported `i`. The token is
    // only HMAC-signed, so a forged token (one precondition: a leaked PYRMI_SECRET) could otherwise carry a genuine
    // session id with a backdated `i` to fake elapsed time and slip past minDurationMs / dilute maxScorePerSec — the
    // real server-side anti-bot floor. Fall back to the token `i` only when no genuine session record backs the
    // token (that path is already penalised as no_client below) (M9).
    const started = genuineSess ? num(sess.i, t.i) : t.i;
    // A genuine token's `i` is copied from the session at creation, so it must equal the stored start. A mismatch
    // means the token was forged or edited — refuse it outright (M9).
    if (genuineSess && num(sess.i, t.i) !== t.i) hard('invalid_token', 'token start does not match the session record');
    const elapsed = now - started;
    // The 2 s grace is for clock skew on impossible_time only. Limits use the shorter of the claimed and the real
    // time, so a claimed duration can't satisfy minDurationMs or dilute maxScorePerSec (A2-03).
    const dur = durationMs === null ? elapsed : Math.min(durationMs, elapsed);
    if (durationMs !== null && durationMs > elapsed + 2000) hard('impossible_time', Math.round(durationMs / 1000) + 's run in a ' + Math.round(elapsed / 1000) + 's session');
    if (dur < s.minDurationMs) hard('too_short');
    if (hasScore && s.maxScore !== null && score > s.maxScore) hard('score_over_max', score + ' > ' + s.maxScore);
    if (hasScore && s.maxScorePerSec !== null && Number.isFinite(score) && score / Math.max(dur / 1000, 1) > s.maxScorePerSec) hard('score_too_fast', (score / Math.max(dur / 1000, 1)).toFixed(2) + '/s');
    const rp = body.replay && typeof body.replay === 'object' ? body.replay : null;
    if (rp && rp.check === 'mismatch') hard('replay_mismatch', String(rp.detail || '').slice(0, 120));
    if (genuineSess) { reasons.push(...assess(sess, s, durationMs)); genuine = true; }
    else reasons.push({ code: 'no_client', weight: WEIGHTS.no_client, detail: 'session record missing' });
  }

  const isHard = reasons.some((r) => HARD.has(r.code));
  const risk = isHard ? 100 : Math.min(100, reasons.reduce((a, r) => a + r.weight, 0));
  const verdict = isHard || risk >= s.rejectAt ? 'reject' : risk >= s.reviewAt ? 'review' : 'accept';
  reasons.sort((a, b) => b.weight - a.weight);
  const replayCheck = body.replay && ['match', 'mismatch', 'none'].includes(body.replay.check) ? body.replay.check : 'none';
  const ev = { t: now, sid, player, score: Number.isFinite(score) ? score : null, durationMs, verdict, risk, replay: replayCheck, reasons: reasons.map((r) => r.detail ? { code: r.code, detail: String(r.detail).slice(0, 120) } : { code: r.code }) };
  await logVerdict(project.pid, ev, genuine);
  return { ok: true, verdict, risk, reasons: reasons.map((r) => ({ code: r.code, weight: r.weight, text: REASONS[r.code], detail: r.detail })), session: sid, player, score: ev.score };
}

async function logVerdict(pid, ev, genuine) {
  const isDemo = pid === DEMO.pid;
  const day = ymd(ev.t), stat = 'ps:st:' + pid + ':' + day, pl = 'ps:pl:' + pid + ':' + ev.player;
  const flagged = ev.verdict !== 'accept';
  const cmds = [
    ['LPUSH', 'ps:ev:' + pid, JSON.stringify(ev)], ['LTRIM', 'ps:ev:' + pid, 0, MAX_EVENTS - 1],
    ['HINCRBY', stat, ev.verdict, 1], ['EXPIRE', stat, 35 * DAY],
    ['HSET', 'ps:p:' + pid, 'lv', ev.t], // "your server is connected" on the dashboard
  ];
  for (const r of ev.reasons) cmds.push(['HINCRBY', stat, 'r:' + r.code, 1]);
  // The per-visitor records are keyed on a caller-chosen label. Only write them when a genuine session backs the
  // verdict; otherwise anyone could spray labels through the keyless /demo endpoint and grow the store unbounded (A2-06).
  if (genuine) {
    // The public sandbox lets anyone pick the visitor label, so per-player detail hashes would grow without bound
    // there (F-19). Never keep them for the demo project; the recent/flagged indexes below are capped on their own.
    if (!isDemo) {
      cmds.push(['HINCRBY', pl, ev.verdict, 1], ['HSET', pl, 'last', ev.t, 'risk', ev.risk, 'top', (ev.reasons[0] && ev.reasons[0].code) || '']);
      cmds.push(['EXPIRE', pl, 30 * DAY]);
    }
    cmds.push(['ZADD', 'ps:plr:' + pid, ev.t, ev.player]);
    // For the demo the recent-players index is self-bounded here (nothing else to clean up). For real projects the
    // index is trimmed in trimPlayers below, which also deletes the detail hash of anyone it evicts, so ps:pl stays
    // capped at MAX_PLAYERS and can't grow without bound either (F-19).
    if (isDemo) cmds.push(['ZREMRANGEBYRANK', 'ps:plr:' + pid, 0, -1001]);
    if (flagged) {
      cmds.push(['ZINCRBY', 'ps:plf:' + pid, 1, ev.player]);
      // Cap the flagged-players set to the worst ~1000, so a flood of one-off names can't grow it without bound (F-08).
      cmds.push(['ZREMRANGEBYRANK', 'ps:plf:' + pid, 0, -1001]);
    }
  }
  await kv.pipeline(cmds);
  if (genuine && !isDemo) await trimPlayers(pid);
}

// Keep a real project's recent-players index at MAX_PLAYERS and delete the per-player detail hash of each player
// trimmed out, so ps:pl is capped the same way the index is (F-19). Does nothing until the project passes the cap.
async function trimPlayers(pid) {
  const over = num(await kv.cmd('ZCARD', 'ps:plr:' + pid), 0) - MAX_PLAYERS;
  if (over <= 0) return;
  const gone = (await kv.cmd('ZRANGE', 'ps:plr:' + pid, 0, over - 1)) || []; // the oldest members
  if (!gone.length) return;
  await kv.pipeline([
    ['DEL', ...gone.map((m) => 'ps:pl:' + pid + ':' + m)],
    ['ZREMRANGEBYRANK', 'ps:plr:' + pid, 0, over - 1],
  ]);
}

